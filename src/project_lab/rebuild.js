// Only structure is handed to the implementer: no decompiled code, no strings.
const SPEC_FACT_CATEGORIES = new Set(['export', 'import', 'dependency', 'call', 'function', 'module', 'external', 'entry', 'arch', 'member']);

export const shQuote = (s) => `'${String(s).replace(/'/g, `'\\''`)}'`;

const norm = (s) => String(s ?? '').replace(/\r\n/g, '\n').replace(/\s+$/, '');

export function compareBehavior(expected, actual) {
  const reasons = [];
  if (expected.exit_code !== undefined && expected.exit_code !== null && actual.exit_code !== expected.exit_code) reasons.push(`exit code ${actual.exit_code} (expected ${expected.exit_code})`);
  if (expected.stdout !== undefined && expected.stdout !== null && norm(actual.stdout) !== norm(expected.stdout)) reasons.push('stdout differs');
  return { match: reasons.length === 0, reasons };
}

export function referenceIdentity(reference) {
  const st = statSync(reference);
  if (st.isDirectory()) {
    const d = treeDigest(reference);
    return { kind: 'directory', name: reference.split('/').pop(), sha256: d.sha256, files: d.files, bytes: d.bytes };
  }
  return { kind: 'file', name: reference.split('/').pop(), sha256: createHash('sha256').update(readFileSync(reference)).digest('hex'), bytes: st.size };
}

// Lines of at least `minLength` characters present in both trees (a copy indicator).
export function verbatimOverlap(referenceDir, workspace, { minLength = 50 } = {}) {
  const lines = new Map();
  for (const f of walkFiles(referenceDir)) {
    if (f.type !== 'file' || f.size > 1_000_000) continue;
    let text;
    try {
      text = readFileSync(f.full, 'utf8');
    } catch {
      continue;
    }
    if (text.includes('\0')) continue;
    for (const raw of text.split('\n')) {
      const l = raw.trim();
      if (l.length >= minLength && !/^(\/\/|#|\*|\/\*)/.test(l)) lines.set(l, f.rel);
    }
  }
  const hits = [];
  for (const f of walkFiles(workspace)) {
    if (f.type !== 'file' || f.size > 1_000_000 || f.rel === 'SPEC.md') continue;
    let text;
    try {
      text = readFileSync(f.full, 'utf8');
    } catch {
      continue;
    }
    for (const raw of text.split('\n')) {
      const l = raw.trim();
      if (l.length >= minLength && lines.has(l)) hits.push({ file: f.rel, from: lines.get(l), line: l.slice(0, 80) });
    }
  }
  return hits;
}

export function buildSpec({ project, identity, detection, analysis, behaviors, unknowns, assumptions }) {
  const facts = (analysis?.facts ?? []).filter((f) => SPEC_FACT_CATEGORIES.has(f.slice(0, f.indexOf(':')))).slice(0, 200);
  const lines = [
    '# Reconstruction specification',
    '',
    '_Generated by ERA from REA evidence and observed behavior. This document is the ONLY description of the reference you are given._',
    '',
    '## Purpose',
    '',
    project.task,
    '',
    '## Authorization',
    '',
    project.authorization,
    '',
    '## Reference (identity only)',
    '',
    `- ${identity.kind}: \`${identity.name}\`, sha256 \`${identity.sha256}\`${identity.files ? `, ${identity.files} files` : ''}`,
    `- ERA detected: ${detection ? `${detection.kind} (${detection.reason})` : 'n/a'}; REA analysis ${analysis ? `${analysis.status}` : 'not available'}.`,
    '',
    '## Observed structure (from REA)',
    '',
    ...(facts.length ? facts.map((f) => `- \`${f}\``) : ['- No structural facts were recovered.']),
    '',
    '## Required behavior',
    '',
    behaviors.length ? '| Name | Arguments | Stdin | Expected stdout | Expected exit | Source |\n|---|---|---|---|---|---|' : 'No behaviors were specified; acceptance relies on the commands and tests listed below.',
    ...behaviors.map((b) => `| ${b.name} | ${b.args.map((a) => `\`${a}\``).join(' ') || '—'} | ${b.stdin === null ? '—' : `\`${JSON.stringify(b.stdin)}\``} | \`${JSON.stringify(b.expected.stdout)}\` | ${b.expected.exit_code} | ${b.source} |`),
    '',
    '## How the implementation will be run',
    '',
    project.commands.run ? `- Behaviors are run as: \`${project.commands.run} <arguments>\` from the project root.` : '- No run command was configured.',
    ...project.acceptance.commands.map((a) => `- Acceptance command: \`${a.command}\``),
    ...project.acceptance.criteria.map((a) => `- ${a}`),
    '',
    '## Unknowns',
    '',
    ...(unknowns.length ? unknowns.map((u) => `- ${u}`) : ['- none recorded']),
    '',
    '## Assumptions',
    '',
    ...assumptions.map((a) => `- ${a}`),
    '',
    '## Clean-room rules',
    '',
    '- Write an original, independent implementation. Do not reproduce code, text, graphics, audio or other protected material of the reference.',
    '- You have no access to the reference; implement from this specification only.',
    '- Do not edit this file.',
  ];
  return lines.join('\n');
}

