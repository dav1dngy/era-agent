const RASTER = /\.(png|jpe?g|webp)$/i;

// Static checks on the generated site, then the sandboxed render-and-compare. Returns reasons/warnings and the visual facts.
async function checkScreenshotSite(c, { images, visualCfg, renderer, attempt }) {
  const reasons = [];
  const warnings = [];
  const entry = join(c.workspace, visualCfg.entry);
  if (!existsSync(entry)) reasons.push(`${visualCfg.entry} was not created. The page must be at that path (acceptance.visual.entry).`);
  const external = externalResourceFindings(c.workspace);
  if (external.length) reasons.push(`These files load resources over the network, which is not allowed (the page is verified offline): ${external.join(', ')}.`);
  const refHashes = new Set(images.flatMap((i) => [i.sha256, i.original_sha256]));
  for (const f of walkFiles(c.workspace)) {
    if (f.type !== 'file' || f.size > 12_000_000) continue;
    if (RASTER.test(f.rel) && refHashes.has(createHash('sha256').update(readFileSync(f.full)).digest('hex'))) reasons.push(`${f.rel} is a copy of the reference screenshot. The page must be built from HTML and CSS, not from the picture.`);
    else if (/\.(html?|css|js|svg)$/i.test(f.rel) && f.size < 5_000_000) {
      for (const m of readFileSync(f.full, 'utf8').matchAll(/data:image\/[a-z+]+;base64,([A-Za-z0-9+/=]{2000,})/g)) {
        if (refHashes.has(createHash('sha256').update(Buffer.from(m[1], 'base64')).digest('hex'))) reasons.push(`${f.rel} embeds the reference screenshot as a data URI.`);
      }
    }
  }
  let visual = null;
  if (images.length > 1) warnings.push(`${images.length} screenshots were provided; only the first (${images[0].name}) is scored. The others are context for the implementer.`);
  if (!renderer) warnings.push('Visual comparison was NOT performed: no renderer is installed here (run npm install in apps/studio, or start ERA from the Studio app). Only your commands were checked.');
  else if (existsSync(entry)) {
    const outDir = join(c.runDir, `visual-attempt-${attempt}`);
    const res = await renderAndCompare({ renderer, htmlPath: entry, referencePath: images[0].path, outDir, assetsDir: c.workspace, width: visualCfg.width, height: visualCfg.height, isolation: c.isolation(), denyRead: c.denyRead() });
    if (!res.ok) reasons.push(`The page could not be rendered for comparison: ${res.error}`);
    else {
      visual = { score: res.score, threshold: visualCfg.threshold, metrics: res.metrics, rendered: `visual-attempt-${attempt}/rendered.png`, reference: `reference-images/${images[0].name}`, entry: visualCfg.entry, page: res.page, blocked_requests: res.blocked_requests, console_errors: res.console_errors, max_asset_similarity: res.max_asset_similarity, renderer: renderer.source, passed: false };
      const hints = visualHints(res.metrics);
      if (res.score < visualCfg.threshold) reasons.push(`The rendered page is not similar enough to the screenshot: score ${res.score} (required ${visualCfg.threshold}; layout ${res.metrics.layout}, edges ${res.metrics.edges}, color ${res.metrics.color}, brightness ${res.metrics.luminance}).${hints.length ? ` Hints: ${hints.join('; ')}.` : ''}`);
      if (res.max_asset_similarity >= visualCfg.maxAssetSimilarity) reasons.push('An image in the project is nearly identical to the reference screenshot: the page must not be built from a copy of it.');
      if (Math.max(res.page.max_image_coverage, res.page.max_background_image_coverage) > visualCfg.maxImageCoverage) reasons.push('A single picture covers most of the page. Build the layout from HTML and CSS instead of a large image.');
      if (res.blocked_requests.length) reasons.push(`The page tried to load ${res.blocked_requests.length} resource(s) it is not allowed to (for example ${res.blocked_requests[0]}).`);
      if (res.page.text_length < 20) warnings.push('The rendered page shows almost no text.');
      if (res.console_errors.length) warnings.push(`The page logged ${res.console_errors.length} console error(s): ${res.console_errors[0]}`);
      visual.passed = res.score >= visualCfg.threshold && !reasons.some((r) => /picture|copy|nearly identical|tried to load/.test(r));
    }
  }
  return { reasons, warnings, visual };
}

export function assertRebuildCriteria(project, { screenshot = false, renderer = null } = {}) {
  const a = project.acceptance;
  if (screenshot) {
    if (a.behaviors.some((b) => b.capture === 'reference')) throw new Error('A screenshot reference has no program to run, so behaviors cannot be captured from it. State the expected output yourself (acceptance.behaviors[].expect) or use acceptance commands.');
    if (!renderer && !a.commands.length && !project.commands.test.length) throw new Error('A screenshot rebuild cannot be verified here: no renderer is installed for the visual comparison (run npm install in apps/studio, or start ERA from the Studio app) and no acceptance command or test command is configured. Add one of them; otherwise any page would count as success.');
    if (a.behaviors.length && !project.commands.run) throw new Error('Behavioral acceptance needs commands.run (how to start the new implementation; arguments are appended).');
    return;
  }
  if (!a.behaviors.length && !a.commands.length && !project.commands.test.length) {
    throw new Error('Rebuild needs at least one acceptance check: acceptance.behaviors, acceptance.commands or commands.test. Without one, any output would count as success.');
  }
  if (a.behaviors.length && !project.commands.run) throw new Error('Behavioral acceptance needs commands.run (how to start the new implementation; arguments are appended).');
}

export async function runRebuild(c) {
  const { project } = c;
  const imagePaths = imageReferencePaths(project.reference);
  const screenshot = !!imagePaths;
  const renderer = screenshot ? findRenderer() : null;
  assertRebuildCriteria(project, { screenshot, renderer });
  const visualCfg = { ...DEFAULT_VISUAL, ...(project.acceptance.visual ?? {}) };
  const agentImages = screenshot ? c.agentImageSupport() : 'none';

  const identity = await c.step('reference', async () => {
    if (screenshot) {
      // Validated, metadata-stripped copies: these (not the originals) are what an agent may see.
      const images = prepareReferenceImages(imagePaths, join(c.runDir, 'reference-images'));
      const sha256 = createHash('sha256').update(images.map((i) => i.sha256).join(',')).digest('hex');
      c.run.reference_digest = sha256;
      c.save();
      return { identity: { kind: 'screenshots', name: images.length === 1 ? basename(project.reference) : `${images.length} screenshots`, sha256, files: images.length }, detection: { kind: 'screenshot', supported: false, reason: 'screenshots are examined visually by the coding agent; REA has no workflow for images' }, images };
    }
    const id = referenceIdentity(project.reference);
    const detection = detectTarget(project.reference);
    c.run.reference_digest = id.sha256;
    c.save();
    return { identity: id, detection };
  });

  const analysis = await c.step('evidence', async () => {
    if (screenshot) return { available: false, reason: 'REA is not applicable to screenshots (they contain no executable structure); the specification comes from the images and your task.', limitations: [] };
    if (!identity.detection.supported) return { available: false, reason: `ERA has no verified REA workflow for this reference (${identity.detection.reason}); the specification relies on the stated behaviors only.`, limitations: [] };
    const status = await c.rea.status();
    const a = await analyzeTarget(project.reference, { rea: c.rea, stateDir: c.runDir, decompile: identity.detection.kind === 'mach-o' && !!status.decompiler_available, maxDecompiledFunctions: c.config.analysis?.maxDecompiledFunctions ?? 8 });
    return {
      available: true,
      status: a.status,
      kind: a.target.kind,
      facts: a.facts,
      fact_groups: a.fact_groups,
      runs: a.runs.map((r) => ({ run_id: r.run_id, label: r.label, status: r.status, evidence_id: r.evidence_id, errors: r.errors })),
      evidence_ids: a.runs.map((r) => r.evidence_id).filter(Boolean),
      limitations: a.evidence.flatMap((e) => e.limitations ?? []),
      residual_unknowns: a.evidence.reduce((s, e) => s + (e.unknowns ?? 0), 0),
      decompiled: a.runs.some((r) => r.label.startsWith('decompile:') && r.status === 'succeeded'),
    };
  });

  const behaviors = await c.step('behaviors', () => (screenshot ? [] : captureReferenceBehaviors(c, project.reference)));

  const spec = await c.step('spec', async () => {
    if (screenshot) {
      const unknowns = ['Interactions, hover states, animations and any content not visible in the screenshot are unknown.', 'Text that is too small or blurry to read may be wrong.', 'Exact fonts and image content are unknown; similar system fonts and neutral stand-ins are expected.', 'Behavior at other screen sizes is unknown.'];
      const assumptions = ['The screenshot shows the intended final design at its natural size.', 'The primary screenshot is scored; similarity is a heuristic, not a pixel-exact match.', 'The page is rendered offline in a sandbox with no network access.'];
      const text = buildScreenshotSpec({ project, images: identity.images, unknowns, assumptions, visual: visualCfg });
      c.writeArtifact('SPEC.md', text);
      return { text, unknowns, assumptions, path: join(c.runDir, 'SPEC.md') };
    }
    const unknowns = [...new Set(analysis.limitations ?? [])].slice(0, 8);
    if (analysis.residual_unknowns) unknowns.push(`REA reports ${analysis.residual_unknowns} residual unknowns in its static graph.`);
    if (!analysis.available) unknowns.push(analysis.reason);
    else if (identity.detection.kind === 'mach-o' && !analysis.decompiled) unknowns.push('No decompilation was available; internal logic was not examined, only structure and observed behavior.');
    unknowns.push('Behavior outside the listed observations is unknown.');
    const assumptions = ['Only the listed behaviors must match exactly; other behavior is the implementer\'s design.', 'Standard output is compared after normalizing line endings and trailing whitespace.', 'The reference was executed only inside a sandbox (no network, writes confined to a scratch directory) when behavior was captured.'];
    const text = buildSpec({ project, identity: identity.identity, detection: identity.detection, analysis: analysis.available ? analysis : null, behaviors, unknowns, assumptions });
    c.writeArtifact('SPEC.md', text);
    return { text, unknowns, assumptions, path: join(c.runDir, 'SPEC.md') };
  });

  const ws = await c.step('workspace', async () => {
    removeWorkspace(c.workspace);
    mkdirSync(c.workspace, { recursive: true });
    writeFileSync(join(c.workspace, 'SPEC.md'), spec.text);
    return { baseline_commit: await initBaseline(c.workspace, 'scaffold: specification'), source_digest: null };
  });

  // SPEC.md is the specification the agent works from; it must not be edited by the agent or by any command.
  const guardProject = { ...project, protected: [...project.protected, 'SPEC.md'] };
  let last = null;
  let commands = { build: [], test: [] };
  for (let n = 1; n <= project.limits.maxAttempts; n++) {
    const impl = await c.step(`implement-${n}`, async () => {
      if (c.agent().id === 'manual') {
        const changes = await workspaceChanges(c.workspace, ws.baseline_commit);
        if (changes.files.length === 0) throw new Pause(`No agent is configured (manual mode). Implement the specification (${join(c.workspace, 'SPEC.md')}) in ${c.workspace}, then run \`era project resume ${project.id}\`.`);
        return { manual: true, agent: 'manual' };
      }
      const feedback = last ? failureFeedback(last.decision, last.verification) : null;
      const r = await c.invokeAgent({ phase: 'rebuild', attempt: n, images: screenshot ? identity.images : [], prompt: screenshot ? screenshotPrompt({ project, spec: spec.text, images: identity.images, feedback, attempt: n, visual: visualCfg, agentImages }) : rebuildPrompt({ project, spec: spec.text, feedback, attempt: n }) });
      return { ...r, output: undefined };
    });
    const verify = await c.step(`verify-${n}`, async () => {
      const changes = await workspaceChanges(c.workspace, ws.baseline_commit);
      if (changes.files.length === 0) return { decision: { pass: false, reasons: [impl.ok === false ? `The coding agent failed (exit ${impl.exit_code}) and created nothing.` : 'The coding agent created no files.'], warnings: [] }, verification: { build: [], test: [], acceptance: [], tests: null }, behaviors: [], changed: [] };
      const detection = await detectProject(c.workspace);
      commands = resolveCommands(project, detection);
      const verification = await runVerification(c, commands, { acceptance: true });
      const site = screenshot ? await checkScreenshotSite(c, { images: identity.images, visualCfg, renderer, attempt: n }) : null;
      const results = [];
      for (const b of behaviors) {
        const r = await c.command(`${project.commands.run} ${b.args.map(shQuote).join(' ')}`.trim(), { input: b.stdin });
        const cmp = compareBehavior(b.expected, { stdout: r.stdout, exit_code: r.exit_code });
        results.push({ name: b.name, args: b.args, match: cmp.match && !r.timed_out, reasons: r.timed_out ? ['timed out'] : cmp.reasons, expected: b.expected, actual: { stdout: r.stdout.slice(0, 2000), exit_code: r.exit_code }, source: b.source });
      }
      // The baseline is the (empty) scaffold: any build/test failure now is a failure.
      const empty = { build: [], test: [], acceptance: [], build_ok: true, test_ok: true, tests: null };
      // Build, test, behavior and rendering commands ran inside the working copy: judge and hash the state that exists now.
      const settled = await workspaceChanges(c.workspace, ws.baseline_commit);
      const decision = evaluateChange({ project: guardProject, baseline: empty, after: verification, changes: settled });
      const touched = changedByCommands(changes, settled);
      if (touched.length) decision.warnings.push(`The build/test/acceptance/behavior commands changed the working copy: ${touched.slice(0, 8).join(', ')}. The guards were applied to the final state.`);
      for (const r of results) if (!r.match) decision.reasons.push(`Behavior "${r.name}" does not match: ${r.reasons.join(', ')}.`);
      if (site) {
        decision.reasons.push(...site.reasons);
        decision.warnings.push(...site.warnings);
      }
      decision.pass = decision.reasons.length === 0;
      if (!screenshot && statSync(project.reference).isDirectory()) {
        const overlap = verbatimOverlap(project.reference, c.workspace);
        if (overlap.length >= 3) {
          decision.reasons.push(`${overlap.length} long lines are identical to the reference (for example ${overlap[0].file}: "${overlap[0].line}…"). The implementation must be independent.`);
          decision.pass = false;
        }
      }
      return { decision, verification, behaviors: results, visual: site?.visual ?? null, changed: settled.files, stat: settled.stat, patch_sha256: patchSha256(settled) };
    });
    last = verify;
    c.run.attempts = [...c.run.attempts.filter((a) => a.n !== n), { n, agent: impl.agent, ok: impl.ok ?? true, pass: verify.decision.pass, reasons: verify.decision.reasons, cost_usd: impl.cost_usd ?? null }];
    c.save();
    if (verify.decision.pass) break;
    if (c.agent().id === 'manual') {
      c.reset(`implement-${n}`, `verify-${n}`);
      throw new Pause(`Acceptance failed:\n- ${verify.decision.reasons.join('\n- ')}\nFix the files in ${c.workspace}, then run \`era project resume ${project.id}\`.`);
    }
  }

  return c.step('finalize', async () => {
    const changes = await workspaceChanges(c.workspace, ws.baseline_commit);
    const patchFile = join(c.runDir, 'change.patch');
    if (changes.patch) writePatch(patchFile, changes.patch);
    // The decision must describe exactly what approval will copy out: re-apply the guards to the final state and refuse a
    // state that was never verified.
    const reasons = [...last.decision.reasons, ...changeGuards({ project: guardProject, changes }).filter((r) => !last.decision.reasons.includes(r))];
    if (last.patch_sha256 && last.patch_sha256 !== patchSha256(changes)) reasons.push('The working copy changed after the last verification, so the final result was never verified. Run `era project resume` to verify it.');
    return {
      pass: reasons.length === 0,
      reasons,
      warnings: last.decision.warnings,
      files: changes.files,
      stat: changes.stat,
      patch_file: existsSync(patchFile) ? patchFile : null,
      patch_sha256: patchSha256(changes),
      baseline_commit: ws.baseline_commit,
      attempts: c.run.attempts.length,
      behaviors: last.behaviors,
      visual: last.visual ?? null,
      screenshot: screenshot ? { images: identity.images.map(({ path: _p, ...rest }) => rest), renderer: renderer?.source ?? null } : null,
      verification: last.verification ? { build: last.verification.build, test: last.verification.test, acceptance: last.verification.acceptance, tests: last.verification.tests } : null,
      summary: summarizeCommands(last.verification ?? { build: [], test: [], acceptance: [] }),
      commands_resolved: commands,
    };
  });
}

