async function captureReferenceBehaviors(c, reference) {
  const out = [];
  const scratch = join(c.runDir, 'reference-scratch');
  mkdirSync(scratch, { recursive: true });
  for (const b of c.project.acceptance.behaviors) {
    if (b.capture !== 'reference') {
      out.push({ name: b.name, args: b.args, stdin: b.stdin, expected: { stdout: b.expect.stdout, exit_code: b.expect.exit_code ?? 0 }, source: 'specified' });
      continue;
    }
    if (!statSync(reference).isFile()) throw new Error(`Behavior "${b.name}" asks to capture the reference, but the reference is not an executable file.`);
    const r = await c.command(`${shQuote(reference)} ${b.args.map(shQuote).join(' ')}`.trim(), { cwd: scratch, input: b.stdin });
    if (r.spawn_error || r.timed_out || r.exit_code === null) throw new Error(`Could not capture behavior "${b.name}" from the reference: ${r.spawn_error ?? (r.timed_out ? 'timed out' : 'did not start')}.`);
    out.push({ name: b.name, args: b.args, stdin: b.stdin, expected: { stdout: r.stdout, exit_code: r.exit_code }, source: 'reference-run (sandboxed)' });
  }
  return out;
}


