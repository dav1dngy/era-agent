#!/usr/bin/env node
// Regenerates THIRD_PARTY_NOTICES.md from package-lock.json and REA's license.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const lock = JSON.parse(readFileSync('package-lock.json', 'utf8'));
const rows = Object.entries(lock.packages)
  .filter(([k, v]) => k.startsWith('node_modules/') && !v.dev)
  .map(([k, v]) => ({ name: k.slice(k.lastIndexOf('node_modules/') + 13), version: v.version, license: v.license ?? 'UNKNOWN' }))
  .sort((a, b) => a.name.localeCompare(b.name));
let reaLicense = null;
try {
  reaLicense = readFileSync(join(dirname(createRequire(import.meta.url).resolve('rea-agents/package.json')), 'LICENSE'), 'utf8');
} catch {
  for (const p of [process.env.REA_LICENSE_FILE].filter(Boolean)) if (existsSync(p)) reaLicense = readFileSync(p, 'utf8');
}
if (!reaLicense) throw new Error('REA LICENSE not found: run `npm install` first or set REA_LICENSE_FILE.');
const studioLock = JSON.parse(readFileSync('apps/studio/package-lock.json', 'utf8'));
const studioRows = Object.entries(studioLock.packages)
  .filter(([k, v]) => k.startsWith('node_modules/') && (!v.dev || k === 'node_modules/electron'))
  .map(([k, v]) => ({ name: k.slice(k.lastIndexOf('node_modules/') + 13), version: v.version, license: v.license ?? 'UNKNOWN' }))
  .sort((a, b) => a.name.localeCompare(b.name));
const counts = rows.reduce((m, r) => ({ ...m, [r.license]: (m[r.license] ?? 0) + 1 }), {});
const out = `# Third-party notices

ERA is MIT-licensed (see LICENSE). This file lists the software ERA depends on.
Generated by \`node scripts/third-party-notices.mjs\` from \`package-lock.json\`.

## Original upstream engine: Reverse Engineer Anything (REA)

ERA integrates and executes **Reverse Engineer Anything** (npm \`rea-agents\`,
<https://github.com/morluto/rea>) as its reverse-engineering engine. ERA does
not copy, vendor or modify REA source code. Everything under \`src/\` is
ERA-specific; REA is installed as the dependency \`rea-agents@${lock.packages['node_modules/rea-agents']?.version}\`.
REA's own bundled third-party components are listed in its package
(\`node_modules/rea-agents/licenses/\` and \`third_party/\`).

\`\`\`
${reaLicense.trim()}
\`\`\`

## Runtime dependency tree (${rows.length} packages, installed with rea-agents)

License summary: ${Object.entries(counts).sort((a, b) => b[1] - a[1]).map(([l, n]) => `${l} (${n})`).join(', ')}.

| Package | Version | License |
|---|---|---|
${rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} |`).join('\n')}

## ERA Studio desktop runtime

Studio is optional; CLI users do not install these dependencies. The desktop bundle
contains Electron and the local Preact, htm, Monaco, xterm.js and Inter assets.
Package license texts remain in the distributed node_modules tree; Electron includes
LICENSE and LICENSES.chromium.html in its distribution. The packager is a development
build tool (BSD-2-Clause) and is not bundled in the application.

| Package | Version | License |
|---|---|---|
${studioRows.map((r) => `| ${r.name} | ${r.version} | ${r.license} |`).join('\n')}

## Evidence files

Files under \`tests/fixtures/evidence/\` and \`experiments/\` are outputs of
running REA 6.4.0 (and, where stated, Hopper Disassembler 6.6.0-demo through
REA) against fixtures authored for this repository and against ERA itself.
`;
writeFileSync('THIRD_PARTY_NOTICES.md', out);
console.log(`THIRD_PARTY_NOTICES.md: ${rows.length} packages`);
